#!/bin/bash
# Modified for Headgasket VR, 2026.
set -e

MVK_REV_FILE="$(dirname "$0")/../.headgasket-revision"
MVK_GIT_REV=$(cat "$MVK_REV_FILE")
if [[ ! "$MVK_GIT_REV" =~ ^[0-9a-f]{64}$ ]]; then
    echo "Invalid MoltenVK source revision: $MVK_REV_FILE" >&2
    exit 1
fi
MVK_HDR_FILE="${BUILT_PRODUCTS_DIR}/mvkGitRevDerived.h"
echo "// Auto-generated by MoltenVK" > "${MVK_HDR_FILE}"
echo "static const char* mvkRevString = \"${MVK_GIT_REV}\";" >> "${MVK_HDR_FILE}"

